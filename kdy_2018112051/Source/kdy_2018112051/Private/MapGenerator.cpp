void AMapGenerator::Generate() {
	std::istringstream stream(_data[UKDYGameInstance::Instance()->GetStage() % _data.size()]);
	std::vector<std::string> lines;
	std::string line;
	std::vector<std::pair<int, std::pair<float, float>>> objectPoint;

	while (std::getline(stream, line, '*')) {
		lines.push_back(line);
	}

	int rows = lines.size();
	int cols = lines.empty() ? 0 : lines[0].size();

	int halfRows = rows / 2;
	int halfCols = cols / 2;

	for (int rowIdx = 0; rowIdx < rows; ++rowIdx) {
		for (int colIdx = 0; colIdx < lines[rowIdx].size(); ++colIdx) {
			float posX = (colIdx - halfCols) * 100;
			float posY = (rowIdx - halfRows) * 100;
			int value = lines[rowIdx][colIdx] - '0';
			if (value == 1) {
				if (WallFactory) {
					AWall* wall = GetWorld()->SpawnActor<
						AWall>(WallFactory, FVector(0, posX, -posY), FRotator(0, 0, 0));
				} else {
					UE_LOG(LogTemp, Error, TEXT("WallFactory is NULL!"));
				}
			} else {
				objectPoint.push_back(std::make_pair(value, std::make_pair(posX, -posY)));
			}
		}
	}
	std::random_shuffle(objectPoint.begin(), objectPoint.end());
	int eCounter = 0;
	int iCounter = 0;
	int tCounter = 0;
	for (int i = 0; eCounter + iCounter + tCounter < 16; i++) {
		int value = objectPoint[i].first;
		std::pair<float, float> p = objectPoint[i].second;
		FVector pos(0, p.first, p.second);
		FRotator rot(0, 0, 0);

		switch (value) {
		case 2:
			if (eCounter >= 7) break;
			if (eCounter < 4) GetWorld()->SpawnActor<AEnemy>(EnemyList[eCounter], pos, rot);
			else GetWorld()->SpawnActor<AEnemyFactory>(EnemyFactoryFactory, pos, rot);
			eCounter++;
			break;
		case 3:
			if (iCounter >= 6) break;
			GetWorld()->SpawnActor<AItem>(ItemList[iCounter % ItemList.Num()], pos, rot);
			iCounter++;
			break;
		case 4:
			if (tCounter >= 3) break;
			GetWorld()->SpawnActor<ATrap>(TrapList[tCounter], pos, rot);
			tCounter++;
			break;
		}
		// GetWorld()->SpawnActor();
	}
}


