void AMapGenerator::Generate() {
    std::istringstream stream(_data[Level]);
    std::vector<std::string> lines;
    std::string line;
    std::vector<std::pair<float, float>> emptyPoint;

    while (std::getline(stream, line, '*')) {
        lines.push_back(line);
    }

    int rows = lines.size();
    int cols = lines.empty() ? 0 : lines[0].size();

    int halfRows = rows / 2;
    int halfCols = cols / 2;

    for (int rowIdx = 0; rowIdx < rows; ++rowIdx) {
        for (int colIdx = 0; colIdx < lines[rowIdx].size(); ++colIdx) {
            float posX = (colIdx - halfCols) * 100;
            float posY = (rowIdx - halfRows) * 100;
            int value = lines[rowIdx][colIdx] - '0';
            if (value == 1) {
                if (WallFactory) {
                    AWall* wall = GetWorld()->SpawnActor<AWall>(WallFactory, FVector(0, posX, -posY), FRotator(0, 0, 0));
                } else {
                    UE_LOG(LogTemp, Error, TEXT("WallFactory is NULL!"));
                }
            } else {
                emptyPoint.push_back(std::make_pair(posX, -posY));
            }
        }
    }
    std::random_shuffle(emptyPoint.begin(), emptyPoint.end());
    for (int i = 0; i < 4; i++) {
        std::pair<float, float> ep = emptyPoint[i];
        AEnemyFactory* ef = GetWorld()->SpawnActor<AEnemyFactory>(EnemyFactoryFactory, FVector(0, ep.first, ep.second), FRotator(0, 0, 0));
    }
}


